import assert from 'node:assert/strict';
import { createServer } from '../../src/server.js';
import { makeHost, say } from '../helpers.js';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { host } = makeHost({ script: () => [say('Ready.')] });
host.registry.create({ id: 'scoped', profile: { name: 'Scoped' } });
const server = createServer({ host, live: false, catalog: { list: async () => ({ models: [], providers: [] }), invalidate() {} } });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const box = name => page.locator(`#edit-tools-list input[value="${name}"]`);
  await box('WebReadPublic').waitFor();
  assert.equal(await page.locator('#edit-tools-all').isChecked(), true);
  assert.equal(await box('WebReadPublic').isDisabled(), true, 'every-tool mode locks the list');
  assert.match(await page.locator('#settings-change-note').textContent(), /Changes take effect/, 'loading tools is not an unsaved change');
  await page.locator('#edit-tools-all').uncheck();
  await box('SendToAgent').uncheck();
  await box('OpenScreen').uncheck();
  assert.equal(await box('Remember').isDisabled(), true, 'memory stays on');
  await page.locator('#settings-form button[type=submit]').click();
  await page.getByText('Settings saved', { exact: true }).waitFor();
  const saved = host.registry.get('scoped').profile.allowed_tools;
  assert.ok(Array.isArray(saved) && saved.includes('WebReadPublic') && !saved.includes('SendToAgent') && !saved.includes('OpenScreen'));
  assert.ok(!host.tools.describeFor(host.registry.get('scoped')).some(t => t.name === 'SendToAgent'));
  await page.reload();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await box('SendToAgent').waitFor();
  assert.equal(await box('SendToAgent').isChecked(), false, 'the saved scope is shown again');
  await page.locator('#edit-tools-all').check();
  await page.locator('#settings-form button[type=submit]').click();
  await page.getByText('Settings saved', { exact: true }).waitFor();
  assert.equal(host.registry.get('scoped').profile.allowed_tools, null);
  // Creating a bot shows the same picker, with host-machine tools off by default.
  await page.locator('#new-agent').click();
  const make = name => page.locator(`#create-tools-list input[value="${name}"]`);
  await make('LocalReadFile').waitFor();
  assert.equal(await page.locator('#create-tools-all').isChecked(), false);
  assert.equal(await make('LocalReadFile').isChecked(), false);
  assert.equal(await make('WebReadPublic').isChecked(), true);
  await make('SandboxRunCommand').uncheck();
  await page.locator('#agent-form input[name=name]').fill('Fresh');
  await page.locator('#agent-form button[type=submit]').click();
  await page.getByText('Fresh joined', { exact: true }).waitFor();
  const fresh = host.registry.list().find(a => a.profile.name === 'Fresh').profile.allowed_tools;
  assert.ok(fresh.includes('WebReadPublic') && !fresh.includes('LocalReadFile') && !fresh.includes('SandboxRunCommand'));
  assert.deepEqual(errors, []);
  console.log('PASS: a bot can be limited to chosen tools from Settings or at creation (host tools off by default), the choice survives reload, and every-tool mode restores them.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); await host.close(); }
