import assert from 'node:assert/strict';
import {createServer} from '../../src/server.js';
import {ProviderStore} from '../../src/services/provider-store.js';
import {makeHost,say} from '../helpers.js';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
process.env.BETTER_BOTS_ENV_FILE='/nonexistent/better-bots-ui/env';
const {host}=makeHost({script:()=>[say('done')]});
const providers=new ProviderStore({dir:host.dir});
providers.addProvider({label:'Example',base_url:'https://example.test/v1',key:'fixture-example-key'});
const catalog={list:async()=>({models:[],providers:[]}),invalidate(){}};
const server=createServer({host,providers,catalog,live:false});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const open=async()=>{await page.goto(`http://127.0.0.1:${server.address().port}`);await page.locator('#open-app-settings').click();await page.locator('[data-settings-page=providers]').click();};
 await open();
 await page.getByRole('button',{name:'Change the key for Example',exact:true}).click();
 let row=page.locator('.provider').filter({has:page.getByRole('button',{name:'Change the key for Example',exact:true})});
 await row.getByLabel('Provider name').fill('Renamed');
 await row.getByLabel('Base URL').fill('https://new.example.test/v1');
 await row.getByRole('button',{name:'Save',exact:true}).click();
 await page.getByRole('button',{name:'Change the key for Renamed',exact:true}).waitFor();
 assert.equal(providers.get('example').base_url,'https://new.example.test/v1');
 assert.equal(providers.keyFor('example'),'fixture-example-key');
 await open();
 await page.getByRole('button',{name:'Change the key for Renamed',exact:true}).click();
 row=page.locator('.provider').filter({has:page.getByRole('button',{name:'Change the key for Renamed',exact:true})});
 assert.equal(await row.getByLabel('API key').inputValue(),'');
 await row.getByLabel('Provider name').fill('Discard this');
 await row.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.equal(providers.get('example').label,'Renamed');
 await page.getByLabel('New provider name').fill('Gateway');
 await page.getByLabel('New provider URL').fill('https://gateway.test/v1');
 await page.getByLabel('New provider API key').fill('fixture-gateway-key');
 await page.locator('form.provider-add').filter({has:page.getByLabel('New provider URL')}).getByRole('button',{name:'Add',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[aria-label="New provider URL"]').value==='');
 assert.equal(providers.keyFor('gateway'),'fixture-gateway-key');
 assert.equal(Object.keys(providers.custom()).length,2);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Change the key for Renamed',exact:true}).click();
 assert.ok(await page.locator('#app-settings').evaluate(e=>e.scrollWidth<=e.clientWidth+1));
 await page.screenshot({path:'/tmp/bb-provider-edit-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: edit, blank-key preservation, reload, cancel, adding a provider, mobile layout; no page errors.');
} finally {await browser.close();await new Promise(r=>server.close(r));await host.close();}
